// Command lossmatrix regenerates internal/transcode/LOSS_MATRIX.md from the
// granular loss-key registry in internal/transcode/losses.go (the single
// source of truth for the CLI, the converters, and the generated matrix).
//
// It is invoked by the go:generate directive in losses.go:
//
//	go generate ./internal/transcode
//
// The working directory must be internal/transcode. The drift test
// (loss_matrix_drift_test.go) proves the checked-in matrix never drifts from
// the registry.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/joeycumines/ai-concurrency-shaper/internal/transcode"
)

func main() {
	var b strings.Builder
	b.WriteString("# Loss matrix\n\n")
	b.WriteString("Generated from the granular loss-key registry in `losses.go` by `go generate` —\n")
	b.WriteString("see losses.go. Do not edit this file by hand; the drift test in\n")
	b.WriteString("loss_matrix_drift_test.go proves it never drifts from the registry.\n\n")
	b.WriteString("Every non-portable feature is gated by exactly one granular, direction-specific\n")
	b.WriteString("loss key. The default strict policy rejects every loss; a mapping approves\n")
	b.WriteString("individual keys via `-transcode-allow-loss`.\n\n")
	b.WriteString("| Loss key | Loss description |\n")
	b.WriteString("| --- | --- |\n")
	for _, key := range transcode.RegisteredLossKeys() {
		fmt.Fprintf(&b, "| `%s` | %s |\n", key, transcode.LossKeyDescription(key))
	}
	b.WriteString("\n")
	if err := os.WriteFile("LOSS_MATRIX.md", []byte(b.String()), 0o644); err != nil {
		fatal(fmt.Errorf("write LOSS_MATRIX.md: %w", err))
	}
	fmt.Println("LOSS_MATRIX.md: regenerated from the loss-key registry")
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "lossmatrix:", err)
	os.Exit(1)
}
